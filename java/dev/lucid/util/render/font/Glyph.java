package dev.lucid.util.render.font;

/**
 * Одна буква в атласе.
 *
 * <p>Все размеры хранятся в долях кегля: чтобы получить пиксели, достаточно умножить
 * на нужный размер шрифта. Поэтому один атлас обслуживает любой кегль.</p>
 *
 * <p>Отступы уже переведены в экранную систему координат, где ось Y смотрит вниз, и
 * отсчитываются от базовой линии. У буквы «р» низ хвоста будет положительным, у «А»
 * верх — отрицательным.</p>
 *
 * @param advance  насколько сдвинуть перо после буквы
 * @param left     левый край изображения буквы
 * @param top      верхний край изображения буквы
 * @param right    правый край изображения буквы
 * @param bottom   нижний край изображения буквы
 * @param u0       левый край в атласе
 * @param v0       верхний край в атласе
 * @param u1       правый край в атласе
 * @param v1       нижний край в атласе
 * @param drawable есть ли у буквы изображение: у пробела его нет
 */
public record Glyph(
		float advance,
		float left,
		float top,
		float right,
		float bottom,
		float u0,
		float v0,
		float u1,
		float v1,
		boolean drawable) {

	/** Буква без изображения: только сдвиг пера. */
	public static Glyph blank(float advance) {
		return new Glyph(advance, 0.0F, 0.0F, 0.0F, 0.0F, 0.0F, 0.0F, 0.0F, 0.0F, false);
	}
}
