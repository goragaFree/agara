package dev.lucid.event;

/**
 * База для всех событий клиента.
 *
 * <p>Событие — это просто пакет данных о том, что случилось в игре. Его создаёт тот,
 * кто перехватил момент (миксин или коллбэк Fabric), а получают все подписавшиеся
 * модули — так миксин перестаёт знать имена конкретных модулей.</p>
 *
 * <p>Отмены здесь специально нет. Если событие можно погасить, оно наследуется от
 * {@link CancellableEvent}. Иначе получается ложь: модуль вызывает {@code cancel()},
 * ничего не происходит, и причину приходится искать в чужом коде.</p>
 */
public abstract class Event {

    /** Короткое имя для логов. */
    @Override
    public String toString() {
        return this.getClass().getSimpleName();
    }
}
